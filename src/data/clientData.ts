// Get unique companies for filtering
export const getUniqueCompanies = (): string[] => {
  const companies = clients
    .map(client => client.company)
    .filter((company): company is string => company !== undefined && company !== "")
    .filter((value, index, self) => self.indexOf(value) === index)
    .sort();
  return companies;
};

// Get clients by company
export const getClientsByCompany = (company: string): Client[] => {
  return clients.filter(client => client.company === company);
};

// Get total client count
export const getTotalClientCount = (): number => {
  return clients.length;
};

// Get recent clients (last 30 days)
export const getRecentClients = (): Client[] => {
  const thirtyDaysAgo = new Date();
  thirtyDaysAgo.setDate(thirtyDaysAgo.getDate() - 30);
  
  return clients.filter(client => {
    const clientDate = new Date(client.dateAdded);
    return clientDate >= thirtyDaysAgo;
  });
};